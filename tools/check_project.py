import argparse
import json
import os
import re
from pathlib import Path
import subprocess
import tomllib


ROOT = Path(__file__).resolve().parents[1]
MAX_LINES = 1000


def toml_inline(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_inline(item) for item in value) + "]"
    if isinstance(value, dict):
        fields = (
            f"{toml_inline(key)} = {toml_inline(item)}"
            for key, item in value.items()
        )
        return "{ " + ", ".join(fields) + " }"
    raise ValueError(f"Unsupported Cargo.lock value {value!r}")


def compact_lock(source):
    lock = tomllib.loads(source.read_text(encoding="utf-8"))
    lines = ["# Generated by Cargo. Package entries use one line each."]
    for key, value in lock.items():
        if key == "package":
            lines.append("package = [")
            lines.extend(f"{toml_inline(package)}," for package in value)
            lines.append("]")
        else:
            lines.append(f"{toml_inline(key)} = {toml_inline(value)}")
    compact = "\n".join(lines) + "\n"
    if tomllib.loads(compact) != lock:
        raise ValueError("Compaction changed the lockfile contents")
    if len(lines) > MAX_LINES:
        raise ValueError("Compacted Cargo.lock exceeds the file length limit")
    destination = ROOT / "Cargo.lock"
    pending = destination.with_name("Cargo.lock.new")
    pending.write_text(compact, encoding="utf-8", newline="\n")
    pending.replace(destination)


def check_files():
    paths = subprocess.check_output(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
    ).split(b"\0")
    largest = (0, "")
    violations = []
    for path in sorted(set(paths) - {b""}):
        relative = os.fsdecode(path)
        file = ROOT / relative
        if not file.is_file():
            continue
        contents = file.read_bytes()
        lines = contents.count(b"\n") + bool(contents and not contents.endswith(b"\n"))
        largest = max(largest, (lines, relative))
        if lines > MAX_LINES:
            violations.append(f"{relative} has {lines} lines (limit {MAX_LINES})")
    if violations:
        print("\n".join(violations))
        return 1
    print(f"Largest project file: {largest[1]} ({largest[0]}/{MAX_LINES} lines)")
    return 0


def check_modal_entry_points():
    forbidden = re.compile(r"\b(?:open_dialog|close_dialog|has_active_dialog)\s*\(")
    violations = []
    for path in (ROOT / "crates/desktop/src").rglob("*.rs"):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if forbidden.search(line):
                violations.append(f"{path.relative_to(ROOT)}:{number}: use the shared app modal host")
    if violations:
        print("\n".join(violations))
        return 1
    print("App dialogs use the shared modal host")
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--compact-lock", nargs="?", type=Path, const=ROOT / "Cargo.lock",
        help="Write a compact Cargo.lock, optionally reading a generated lockfile",
    )
    args = parser.parse_args()
    if args.compact_lock is not None:
        compact_lock(args.compact_lock)
    return max(check_files(), check_modal_entry_points())


if __name__ == "__main__":
    raise SystemExit(main())
